"""Recreate case-study folders after cloning: python setup_folders.py.

Uses only Python's standard library. Existing files are preserved. Datasets,
models, predictions, and study databases must be downloaded or generated by
running the corresponding case-study notebooks.
"""

from pathlib import Path


STUDY_FOLDERS = {
    "AdultCensusStudy": (
        "data/raw", "data/splits", "artifacts", "notebooks", "studies",
        "results/adult_evaluation/figures",
        "results/adult_evaluation/predictions",
    ),
    "AmazonEmployeeStudy": (
        "data/raw", "data/splits", "artifacts/input_info", "artifacts/models",
        "artifacts/preprocessors", "notebooks", "optuna", "results/figures",
        "results/predictions", "results/test", "results/validation",
    ),
    "HiggsStudy": (
        "data/raw", "data/splits", "data/processed", "artifacts/input_info",
        "artifacts/models", "notebooks", "results/figures",
        "results/predictions", "results/test", "results/validation",
    ),
    "HomeCreditStudy": (
        "data/raw", "data/splits", "data/processed/engineered",
        "data/processed/engineered_filtered", "data/processed/native/engineered",
        "data/processed/native/engineered_filtered", "artifacts/native",
        "notebooks", "reports", "studies", "results/native",
        "results/home_credit_evaluation/figures",
        "results/home_credit_evaluation/predictions",
    ),
}


def main() -> None:
    root = Path(__file__).resolve().parent
    created = 0
    for study, folders in STUDY_FOLDERS.items():
        for folder in folders:
            target = root / study / folder
            if not target.is_dir():
                target.mkdir(parents=True, exist_ok=True)
                created += 1
    print(f"Folder setup complete: {created} folders created in {root}.")
    print("Existing files were preserved. Dataset and model files are not included.")
    print("Download each dataset into its study's data/raw folder, then run its notebooks.")


if __name__ == "__main__":
    main()
